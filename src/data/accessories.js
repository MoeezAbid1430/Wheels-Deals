export const accessoryFitsVehicle = (accessory, vehicle) => {
  if (!accessory || !vehicle) return false;
  if (accessory.fitmentType === 'Universal') return true;

  const compatibility = accessory.compatibility || {};
  const year = Number(vehicle.year);
  const yearFrom = Number(compatibility.yearFrom) || 0;
  const yearTo = Number(compatibility.yearTo) || 9999;
  const matchesYear = !year || (year >= yearFrom && year <= yearTo);
  const matchesMake = !compatibility.makes?.length || compatibility.makes.includes(vehicle.make);
  const matchesModel = !compatibility.models?.length || compatibility.models.includes(vehicle.model);
  const matchesBody = !compatibility.bodyStyles?.length || compatibility.bodyStyles.includes(vehicle.bodyStyle);

  return matchesYear && matchesMake && matchesModel && matchesBody;
};
