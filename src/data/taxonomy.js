export const getAccessoryFulfillment = (accessory) => {
  const rule = accessoryFulfillmentRules[accessory?.category] || {};
  const usedOrLarge = accessory?.condition === 'Used' || accessory?.category?.includes('Bumper') || accessory?.category?.includes('Rims');
  return {
    fulfillment: accessory?.fulfillment || rule.fulfillment || (usedOrLarge ? 'Pickup / meet seller' : 'Deliverable'),
    installRequired: accessory?.installRequired ?? rule.installRequired ?? false,
    courierAllowed: accessory?.courierAllowed ?? rule.courierAllowed ?? !usedOrLarge,
    meetupRecommended: accessory?.meetupRecommended ?? rule.meetupRecommended ?? usedOrLarge,
  };
};

